"""hao-contract: hygiene, generated.lock and payload-manifest checks, each refusing a seeded violation.
python3 -I -B -m unittest discover -s tests"""
import hashlib
import json
from pathlib import Path
import runpy
import subprocess
import tempfile
import unittest

C = runpy.run_path(str(Path(__file__).resolve().parents[1] / 'hao_contract.py'))
HOME = '/' + 'Users/someone/x'       # built from parts so this file stays clean


def sha(b):
    return hashlib.sha256(b).hexdigest()


class Repo(unittest.TestCase):
    def setUp(self):
        self.r = Path(tempfile.mkdtemp())
        subprocess.run(['git', 'init', '-q', str(self.r)], check=True)
        for k, v in (('user.name', 't'), ('user.email', 't@example.invalid')):
            subprocess.run(['git', '-C', str(self.r), 'config', k, v], check=True)

    def write(self, name, data, commit='add'):
        p = self.r / name
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(data if isinstance(data, bytes) else data.encode())
        subprocess.run(['git', '-C', str(self.r), 'add', name], check=True)
        subprocess.run(['git', '-C', str(self.r), 'commit', '-qm', commit], check=True)

    def contract(self, *checks):
        self.write('contract.json', json.dumps({'contract_version': 1, 'role': 'runtime', 'checks': list(checks)}))
        return C['check'](self.r)


class Hygiene(Repo):
    def test_private_path_in_file_and_commit_message(self):
        self.write('README.md', 'see %s\n' % HOME)
        self.write('ok.txt', 'fine\n', commit='mentions %s' % HOME)
        bad = self.contract({'kind': 'hygiene', 'commits': 5})
        self.assertTrue(any('README.md:1 names a home folder' in b for b in bad), bad)
        self.assertTrue(any('message names a home folder' in b for b in bad), bad)
        bad = self.contract({'kind': 'hygiene', 'allow': {'README.md': ['home folder']}})
        self.assertEqual(bad, [])


class GeneratedLock(Repo):
    STAMPED = '/* Generated by gen_x.py from macOS 27.2.1 (26B131) and its SDK */\nrow;\n'

    def lock(self, **over):
        e = {'path': 'src/x_gen.inc', 'sha256': sha(self.STAMPED.encode()), 'export_id': 'e1', 'os_build': '26B131',
             'cache_uuid': 'U', 'format': 'aggspi/1'}
        e.update(over)
        self.write('generated.lock', json.dumps({'lock_version': 1, 'files': [e]}))

    def test_matching_lock_passes(self):
        self.write('src/x_gen.inc', self.STAMPED)
        self.lock()
        self.assertEqual(self.contract({'kind': 'generated-lock', 'globs': ['src/*_gen.inc']}), [])

    def test_seeded_violations(self):
        self.write('src/x_gen.inc', self.STAMPED + 'hand edit;\n')                     # edited by hand
        self.write('src/y_gen.inc', 'unlisted\n')                                      # not in the lock
        self.lock()
        bad = '\n'.join(self.contract({'kind': 'generated-lock', 'globs': ['src/*_gen.inc']}))
        self.assertIn('x_gen.inc differs from its locked sha256', bad)
        self.assertIn('y_gen.inc is generated but not in generated.lock', bad)

    def test_stamp_for_another_os_build(self):
        old = self.STAMPED.replace('27.2.1 (26B131)', '27.0 (26A428)')
        self.write('src/x_gen.inc', old)
        self.lock(sha256=sha(old.encode()))
        bad = self.contract({'kind': 'generated-lock', 'globs': ['src/*_gen.inc']})
        self.assertEqual(bad, ['generated-lock: src/x_gen.inc is stamped 26A428 but locked as 26B131'])


class Payload(Repo):
    def manifest(self, **over):
        (self.r / 'payload/root/usr/lib').mkdir(parents=True)
        (self.r / 'payload/root/usr/lib/libhao.dylib').write_bytes(b'lib')
        m = {'version': '1', 'commit': '87240c3', 'clean': True, 'os_build': '26B131', 'cache_uuid': 'U',
             'units_version': 'u4.1', 'units_sha256': '0' * 64, 'layout_version': 2,
             'files': {'root/usr/lib/libhao.dylib': sha(b'lib')}}
        m.update(over)
        (self.r / 'payload/payload-manifest.json').write_text(json.dumps(m))
        return {'kind': 'payload', 'manifest': 'payload/payload-manifest.json', 'os_build': '26B131',
                'layout_version': 2}

    def test_good_payload(self):
        self.assertEqual(C['check_payload'](self.r, self.manifest()), [])

    def test_seeded_violations(self):
        c = self.manifest(clean=False, os_build='26A428', layout_version=1)
        (self.r / 'payload/root/usr/lib/libhao.dylib').write_bytes(b'other')
        bad = '\n'.join(C['check_payload'](self.r, c))
        for want in ('dirty tree', 'OS build 26A428, the patcher declares 26B131', 'install-layout version 1',
                     'libhao.dylib does not match'):
            self.assertIn(want, bad)


if __name__ == '__main__':
    unittest.main()
